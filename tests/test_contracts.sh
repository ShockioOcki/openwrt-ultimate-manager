grep -Fq -- '--interface "$device"' "$ZAPRET_STRATEGY"
grep -Fq 'zapret_section()' "$ZAPRET_STRATEGY"
grep -Fq 'https://i.ytimg.com/vi/dQw4w9WgXcQ/hqdefault.jpg' "$ZAPRET_STRATEGY"
! grep -Fq 'zapret.main.NFQWS_OPT' "$ZAPRET_STRATEGY"
