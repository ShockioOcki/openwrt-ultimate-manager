grep -Fq 'applyPodkopRouting' "$RPC"
grep -Fq 'podkopDiagnostics' "$RPC"
grep -Fq 'podkopInstalled()' "$RPC"
grep -Fq 'WS_USER="root"' "$PODKOP"
