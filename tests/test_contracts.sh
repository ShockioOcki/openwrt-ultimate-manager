grep -Fq 'podkop-diagnostic-grid' "$DASHBOARD"
grep -Fq 'podkop-awg-config' "$ROOT/luci-app-oum/htdocs/luci-static/resources/view/oum/settings-v4.js"
grep -Fq 'Reality / Proxy' "$ROOT/luci-app-oum/htdocs/luci-static/resources/view/oum/settings-v4.js"
grep -Fq 'Zapret для YouTube' "$ROOT/luci-app-oum/htdocs/luci-static/resources/view/oum/settings-v4.js"
