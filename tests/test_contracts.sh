grep -Fq 'podkop_awg' "$ROOT/luci-app-oum/root/usr/libexec/oum-system-job"
grep -Fq 'zapret_auto' "$ROOT/luci-app-oum/root/usr/libexec/oum-system-job"
grep -Fq 'startZapretStrategy' "$RPC"
grep -Fq 'zapretStrategyStatus' "$RPC"
grep -Fq 'CATALOG_REVISION=189abafd50aed17f8c7414695d0d47d129a6b0dd' "$ZAPRET_STRATEGY"
